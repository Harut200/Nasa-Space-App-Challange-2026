import fs from 'node:fs'
import assert from 'node:assert/strict'
import * as u from './util.js'
const root = new URL('../../../app/public/data/', import.meta.url)
const rd = (id, f) => JSON.parse(fs.readFileSync(new URL(`${id}/${f}`, root), 'utf8'))
assert.equal(u.fmtDate('2026-10-17'), '17 Oct')
assert.equal(u.fmtNum(5045.9), '5,046')
assert.equal(u.fmtNum(0.3), '0.3')
assert.equal(u.fmtSigned(-12.4), '−12')
assert.equal(u.fmtSigned(0), '0')
assert.equal(u.niceMax(0), 1)
assert.ok(u.niceMax(5045.9) >= 5045.9)
const ts = rd('tonle-sap', 'timeseries.json')
const s = u.placeStats(ts)
assert.equal(s.peak, 5045.9); assert.equal(s.peakDate, '2026-10-17'); assert.equal(s.first, 2280.9)
assert.ok(Math.abs(s.pct - 121.2) < 0.2, s.pct)
const sv = u.placeStats(rd('sevan', 'timeseries.json'))
assert.ok(Math.abs(sv.delta) < 1 && Math.abs(sv.pct) < 0.1)
const ar = u.placeStats(rd('ararat', 'timeseries.json'))
assert.ok(ar.peak < 1)
const ok = u.placeStats(rd('okavango', 'timeseries.json'))
assert.equal(ok.pct, null); assert.equal(ok.delta, 0)
assert.deepEqual(u.placeStats(null), { peak: null, peakDate: null, first: null, last: null, delta: null, pct: null })
const xs = u.makeXScale(ts.dates, 0, 100)
const gx = [u.dayNum('2026-07-25'), u.dayNum('2026-08-18')].map(xs.f)
const reg = xs.f(u.dayNum('2026-07-01')) - xs.f(u.dayNum('2026-06-19'))
assert.ok(gx[1] - gx[0] > 1.9 * reg, 'outage interval must be visibly wider')
assert.equal(u.makeXScale(['2026-01-01'], 0, 10).f(u.dayNum('2026-01-01')), 5)
assert.equal(u.nearestIndex([0, 10, 50], 31), 2)
assert.deepEqual(u.monthTicks(u.dayNum('2026-06-19'), u.dayNum('2026-10-17')).map((t) => t.label), ['Jul', 'Aug', 'Sep', 'Oct'])
const m = rd('ararat', 'manifest.json')
assert.equal(u.qualityFor(m.quality, '2026-10-06').level, 'fail')
assert.equal(u.qualityFor(m.quality, '2026-07-02'), null)
for (const id of JSON.parse(fs.readFileSync(new URL('index.json', root))).areas) {
  const mm = rd(id, 'manifest.json')
  const url = u.thumbUrl(mm, 'data/')
  assert.ok(url && fs.existsSync(new URL(url.replace(/^data\//, ''), root)), `thumb ${id}: ${url}`)
}
console.log('check ok')
